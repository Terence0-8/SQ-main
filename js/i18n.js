/**
 * Récupère la langue actuelle depuis localStorage
 * @returns {string} 'fr' ou 'en', défaut 'fr'
 */
function getLanguage() {
  return localStorage.getItem('siteLanguage') || localStorage.getItem('lang') || 'fr';
}

/**
 * Enregistre la langue sélectionnée dans localStorage ET backend
 * @param {string} lang - 'fr' ou 'en'
 */
async function setLanguage(lang) {
  localStorage.setItem('siteLanguage', lang);
  localStorage.setItem('lang', lang);
  console.log(`🌍 Langue changée: ${lang}`);

  try {
    const apiUrl = window.API_URL || (window.location.origin + '/api');
    await fetch(apiUrl + '/language/preference', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      credentials: 'include',
      body: JSON.stringify({ language: lang })
    });
  } catch (error) {
    console.warn('⚠️ Synchronisation serveur de la langue non disponible');
  }

  return lang;
}

/**
 * Charge la préférence de langue depuis localStorage ou le backend
 * @returns {Promise<string>} La langue préférée ('fr' ou 'en')
 */
async function loadLanguagePreference() {
  const cachedLang = localStorage.getItem('siteLanguage') || localStorage.getItem('lang');
  if (cachedLang) return cachedLang;

  try {
    const apiUrl = window.API_URL || (window.location.origin + '/api');
    const response = await fetch(apiUrl + '/language/preference', { credentials: 'include' });
    const data = await response.json();
    if (data.success && data.language) {
      localStorage.setItem('siteLanguage', data.language);
      localStorage.setItem('lang', data.language);
      return data.language;
    }
  } catch (error) {
    console.warn('⚠️ Impossible de charger la préférence depuis le serveur');
  }

  return 'fr';
}

/**
 * Traduit une clé avec support des variables {{n}}
 * @param {string} key - Clé de traduction
 * @param {Object|string} vars - Variables à remplacer ou texte par défaut
 * @param {string} defaultVal - Texte par défaut si clé introuvable
 * @returns {string} Texte traduit
 */
function t(key, vars = {}, defaultVal = '') {
  const lang = getLanguage();
  if (typeof vars === 'string') {
    defaultVal = vars;
    vars = {};
  }
  
  let text = (TRANSLATIONS[lang] && TRANSLATIONS[lang][key] !== undefined)
    ? TRANSLATIONS[lang][key]
    : (TRANSLATIONS.fr && TRANSLATIONS.fr[key] !== undefined)
      ? TRANSLATIONS.fr[key]
      : (defaultVal || key);

  if (vars && typeof vars === 'object') {
    Object.keys(vars).forEach(varKey => {
      text = text.replace(new RegExp(`{{${varKey}}}`, 'g'), vars[varKey]);
    });
  }

  return text;
}

